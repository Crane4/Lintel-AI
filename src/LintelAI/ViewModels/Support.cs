public enum ScoreBand { None, Good, Fair, Poor }

public static class ScoreBands
{
    public static ScoreBand Of(int? score) => score switch
    {
        null => ScoreBand.None,
        >= 80 => ScoreBand.Good,
        >= 50 => ScoreBand.Fair,
        _ => ScoreBand.Poor
    };
}

